function build(index: 1 | 2): TranslationCatalog {
  const catalog: Record<string, TranslationMessage> = {};
  for (const entry of ENTRIES) {
    const key = P + entry[0];
    if (Object.hasOwn(catalog, key)) throw new Error(`Clave duplicada en teacher-composer: ${key}`);
    catalog[key] = entry[index];
  }
  return catalog;
}

