function build(index: 1 | 2): TranslationCatalog {
  const catalog: Record<string, TranslationMessage> = {};
  for (const entry of ENTRIES) {
    const key = P + entry[0];
    if (Object.hasOwn(catalog, key)) throw new Error(`Clave duplicada en live-board: ${key}`);
    catalog[key] = entry[index];
  }
  return catalog;
}

/**
 * Tipados sin claves literales a propósito: así el spread en EN/ES no añade una firma de índice
 * y se conserva la comprobación `satisfies Record<keyof typeof EN, …>` de es.ts para el resto.
 * La paridad EN=ES de este bloque la garantiza la construcción (misma lista) y su spec.
 */
export const LIVE_BOARD_EN: Readonly<Record<never, never>> = build(1);
export const LIVE_BOARD_ES: Readonly<Record<never, never>> = build(2);
